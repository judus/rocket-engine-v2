"""Bake grayscale source-texture detail beneath the two fitted Hi3D alert discs.
Run from the repository root; requires NumPy and Pillow. No GLB changes.
"""
import base64, hashlib, io, json, struct
from pathlib import Path
import numpy as np
from PIL import Image

asset = Path('examples/3d/assets/cockpit-hi3d-v3-gap-filled.glb')
raw = asset.read_bytes()
length = struct.unpack_from('<I', raw, 12)[0]
gltf = json.loads(raw[20:20 + length])
blob = raw[28 + length:]

def read(index):
    a = gltf['accessors'][index]; view = gltf['bufferViews'][a['bufferView']]
    columns = {'VEC3': 3, 'VEC2': 2, 'SCALAR': 1}[a['type']]
    dtype = {5126: '<f4', 5125: '<u4', 5123: '<u2'}[a['componentType']]
    size = np.dtype(dtype).itemsize
    return np.ndarray((a['count'], columns), dtype=dtype, buffer=blob,
        offset=view.get('byteOffset', 0) + a.get('byteOffset', 0),
        strides=(view.get('byteStride', columns * size), size)).copy()

def matrix(node):
    if 'matrix' in node: return np.array(node['matrix']).reshape(4, 4).T
    x,y,z,w = node.get('rotation', [0,0,0,1])
    rotation = np.array([[1-2*y*y-2*z*z,2*x*y-2*z*w,2*x*z+2*y*w],
        [2*x*y+2*z*w,1-2*x*x-2*z*z,2*y*z-2*x*w],
        [2*x*z-2*y*w,2*y*z+2*x*w,1-2*x*x-2*y*y]])
    result = np.eye(4)
    result[:3,:3] = rotation @ np.diag(node.get('scale',[1,1,1]))
    result[:3,3] = node.get('translation',[0,0,0])
    return result

triangles = []; coords = []; material_ids = []
def visit(index, parent):
    node = gltf['nodes'][index]; transform = parent @ matrix(node)
    if 'mesh' in node:
        for primitive in gltf['meshes'][node['mesh']]['primitives']:
            attrs = primitive['attributes']
            if 'TEXCOORD_0' not in attrs: continue
            vertices = read(attrs['POSITION'])
            vertices = (np.column_stack((vertices, np.ones(len(vertices)))) @ transform.T)[:,:3]
            vertices *= 94.70412249158481
            vertices[:,1] -= .8191118254985987
            indices = read(primitive['indices']).reshape(-1,3) if 'indices' in primitive else np.arange(len(vertices)).reshape(-1,3)
            triangles.append(vertices[indices]); coords.append(read(attrs['TEXCOORD_0'])[indices])
            material_ids.extend([primitive['material']] * len(indices))
    for child in node.get('children',[]): visit(child, transform)
for index in gltf['scenes'][gltf.get('scene',0)]['nodes']: visit(index, np.eye(4))
triangles = np.concatenate(triangles); coords = np.concatenate(coords)
textures = {}
for i, material in enumerate(gltf['materials']):
    texture = material.get('pbrMetallicRoughness',{}).get('baseColorTexture')
    if not texture: continue
    source = gltf['images'][gltf['textures'][texture['index']]['source']]
    view = gltf['bufferViews'][source['bufferView']]
    start = view.get('byteOffset',0)
    textures[i] = np.array(Image.open(io.BytesIO(blob[start:start+view['byteLength']])).convert('RGB'))

eye = np.array([0, (1.48-1.53)/.93+1.5, 2.93])
plane = -.35
projection = eye + (triangles-eye) * ((plane-eye[2]) / (triangles[:,:,2]-eye[2]))[:,:,None]
samples = {}
for name, cx in [('r1',1.29+.009), ('r2',1.75-.038)]:
    cy = 3.405-.058; width = .3*.686*.93/.81; height = .3*.686
    mask = ((projection[:,:,0].max(1)>=cx-width/2) & (projection[:,:,0].min(1)<=cx+width/2)
        & (projection[:,:,1].max(1)>=cy-height/2) & (projection[:,:,1].min(1)<=cy+height/2))
    selected = np.flatnonzero(mask)
    t = triangles[selected]; a=t[:,0]; e1=t[:,1]-a; e2=t[:,2]-a; origin=eye-a
    values=[]; misses=0
    for y in range(32):
        for x in range(32):
            target=np.array([cx+((x+.5)/32-.5)*width, cy+(.5-(y+.5)/32)*height, plane])
            direction=target-eye; p=np.cross(direction,e2); det=(e1*p).sum(1)
            inv=np.divide(1,det,out=np.zeros_like(det),where=abs(det)>1e-12)
            u=inv*(origin*p).sum(1); q=np.cross(origin,e1); v=inv*(q*direction).sum(1)
            distance=inv*(e2*q).sum(1)
            valid=(u>=0)&(v>=0)&(u+v<=1)&(distance>=1-1e-6)&(abs(det)>1e-12)
            if not valid.any(): values.append(255); misses+=1; continue
            k=np.argmin(np.where(valid,distance,np.inf)); index=selected[k]
            uv=coords[index,0]*(1-u[k]-v[k])+coords[index,1]*u[k]+coords[index,2]*v[k]
            image=textures[material_ids[index]]; h,w,_=image.shape
            rgb=image[min(h-1,max(0,int(uv[1]*h))), min(w-1,max(0,int(uv[0]*w)))]
            values.append(round(float(rgb @ np.array([.2126,.7152,.0722]))))
    samples[name]=base64.b64encode(bytes(values)).decode()
    print(name, 'rays',len(values),'misses',misses,'range',min(values),max(values))
header='// Generated by scripts/sample-hi3d-lamp-underlay.py; source base-color luminance.\n'
header+='// GLB SHA256: '+hashlib.sha256(raw).hexdigest()+'\n'
header+='// Fixed accepted pilot fit and disc footprint; this is not real transparency.\n'
output=header+'const patches = '+json.dumps(samples,indent=2)+' as const;\n'
output+='const pixels = Object.fromEntries(Object.entries(patches).map(([name, data]) => [name, Uint8Array.from(atob(data), (c) => c.charCodeAt(0))]));\n'
output+='export function hi3dLampUnderlay(name: string, u: number, v: number): number {\n  const patch = pixels[name];\n  return patch ? patch[Math.min(31, Math.max(0, Math.floor(v * 32))) * 32 + Math.min(31, Math.max(0, Math.floor(u * 32)))]! / 255 : 1;\n}\n'
Path('examples/webgl/Hi3dLampUnderlay.ts').write_text(output)
